# When a single rule fires this many times in one file, collapse to a summary line.
# Users can disable with --no-group.
_GROUP_THRESHOLD = 10

# Patterns indicating a file is auto-generated and should be skipped in recursive --check.
#
# BACK-1195: was anchored to `#`-prefixed comments only, so a C/JS-style
# `/* @generated */` or `// generated` header couldn't match by construction
# (confirmed live, wishlist-3 addendum B3-4). Each pattern now accepts an
# optional `#`, `//`, or `/*` comment lead-in (or none at all, for engines
# that emit a bare marker line).
_COMMENT_LEAD_IN = r'(?:#|//|/\*)?\s*'
_GENERATED_PATTERNS = [
    re.compile(_COMMENT_LEAD_IN + r'reveal:\s*generated', re.IGNORECASE),
    re.compile(_COMMENT_LEAD_IN + r'(this file (is|was)\s+)?(auto[- ]?generated|automatically generated)', re.IGNORECASE),
    re.compile(_COMMENT_LEAD_IN + r'Generated by\b', re.IGNORECASE),
    re.compile(_COMMENT_LEAD_IN + r'@generated\b', re.IGNORECASE),
]


def _is_generated_file(content: str) -> bool:
    """Return True if content appears to be auto-generated (first 15 lines)."""
    head = '\n'.join(split_lines(content)[:15])
    return any(p.search(head) for p in _GENERATED_PATTERNS)


def _python_only_rule_disclosures(files, select, ignore) -> List[str]:
    """BACK-1283: a Python-only rule (T006) is skipped by file pattern on other
    languages, which reads as "checked, clean". Say so when it was in the
    effective rule set and the run held non-Python source."""
    from .capabilities import python_only_rule_disclosure
    from .rules.scan_caches import rule_will_run
    if not rule_will_run("T006", select, ignore):
        return []
    note = python_only_rule_disclosure(files, "T006")
    return [note] if note else []


def _i001_not_checked_disclosures(files, select, ignore) -> List[str]:
    """BACK-1398: I001 runs on every language with an import extractor but only
    judges the ones with unused-import detection; say so for the rest."""
    from .rules.scan_caches import rule_will_run
    if not rule_will_run("I001", select, ignore):
        return []
    from .adapters.imports import _unused_not_checked
    from .analyzers.imports.base import get_all_extensions
    from .capabilities import W_CAP_UNUSED_NOT_CHECKED
    extractable = get_all_extensions()
    not_checked = _unused_not_checked(Path(f) for f in files if Path(f).suffix in extractable)
    if not not_checked:
        return []
    listing = ", ".join(f"{ext} ({n})" for ext, n in not_checked.items())
    return [
        f"{W_CAP_UNUSED_NOT_CHECKED}: I001 has no unused-import detection for these languages; "
        f"{sum(not_checked.values())} file(s) were not checked by it: {listing}."
    ]


def _i002_not_applicable_disclosures(files, select, ignore) -> List[str]:
    """BACK-2156: I002 judges load-time import cycles only where one breaks the program; say
    which files it left out and where their cycles are reported instead."""
    from .rules.scan_caches import rule_will_run
    if not rule_will_run("I002", select, ignore):
        return []
    from .analyzers.imports.base import get_all_extensions
    from .capabilities import (LOAD_ORDER_CYCLE_LANGUAGES, W_CAP_RULE_NOT_APPLICABLE,
                               load_order_cycle_extension)
    from .utils.path_utils import tally_files_by_language
    extractable = get_all_extensions()
    skipped = [Path(f) for f in files
               if Path(f).suffix in extractable and not load_order_cycle_extension(Path(f).suffix)]
    tally = tally_files_by_language(skipped)
    if not tally:
        return []
    ranked = sorted(((lang, v["count"]) for lang, v in tally.items()), key=lambda kv: (-kv[1], kv[0]))
    listing = ", ".join(f"{lang} ({n})" for lang, n in ranked[:5])
    more = f", +{len(ranked) - 5} more" if len(ranked) > 5 else ""
    languages = ", ".join(sorted(LOAD_ORDER_CYCLE_LANGUAGES))
    return [
        f"{W_CAP_RULE_NOT_APPLICABLE}: I002 judges import cycles only where a load-time cycle breaks "
        f"the program ({languages}); {sum(n for _, n in ranked)} file(s) in other languages were "
        f"not checked by it: {listing}{more}. Their cycles: reveal 'imports://<path>?circular'."
    ]


def capability_disclosures(files, select, ignore) -> List[str]:
    """Rules in the effective set that did not look at some of *files* because
    of their language (W-CAP-1 T006, W-CAP-2 I001, W-CAP-3 I002). Shared by single-file and
    recursive ``check`` and by the MCP tool, so none of them can print a bare
    "no issues" the others already know is unearned (BACK-1466)."""
    return (_python_only_rule_disclosures(files, select, ignore)
            + _i001_not_checked_disclosures(files, select, ignore)
            + _i002_not_applicable_disclosures(files, select, ignore)
            + _config_load_disclosures(files))


def _config_load_disclosures(files) -> List[str]:
    """Config files that exist for *files* but could not be loaded (BACK-1857): their rule
    selection, ignores and thresholds were not applied, and the run otherwise reads as a
    check under the user's own settings. One note per file, whichever file reached it."""
    from .config import RevealConfig
    failures: dict = {}
    for directory in sorted({Path(f).parent for f in files}):
        for path, why in RevealConfig.get(directory).load_failures:
            failures.setdefault(path, why)
    return [f"config {path} could not be loaded ({why}): its settings were not applied, "
            "so this run used the defaults for them" for path, why in sorted(failures.items())]


def parse_error_suffix(position: Optional[Tuple[int, int]]) -> str:
    """" (first error at line L:C)" for a degraded parse, "" when none is known
    (BACK-1779). One spelling for every check surface."""
    return f" (first error at line {position[0]}:{position[1]})" if position else ""


def parse_error_description(position: Optional[Tuple[int, int]], reason: Optional[str] = None) -> str:
    """An explicit source failure, otherwise the existing native-recovery description."""
    return reason or f"file did not parse cleanly{parse_error_suffix(position)}"


def _detections_result(
    path: str,
    detections: List[Any],
    parse_degraded: bool = False,
    parse_error_at: Optional[Tuple[int, int]] = None,
    rule_errors: Optional[List[dict]] = None,
    no_snippets: bool = False,
    max_snippet_chars: Optional[int] = None,
    total_available: Optional[int] = None,
    disclosures: Optional[List[str]] = None,
    parse_error_reason: Optional[str] = None,
    coverage: Optional[dict] = None,
) -> dict:
    """The single-file check result as plain data; the subcommand seam
    (emit_subcommand_result / subcommand_json) adds the Output Contract envelope
    (BACK-1702, as BACK-1545 did for ``check <dir>``), so --format json and --also-json
    are one document (BACK-1248).

    A --max-items cut (``total_available`` > ``len(detections)``) is recorded with
    note_truncation (``meta.warnings``; the seam prints it once in text). The
    ``meta.truncated/total_available/returned`` triple stays for compatibility.

    Args:
        path: File path
        detections: Detection objects, already --max-items-truncated by the caller
        parse_degraded: True when the parser recovered from a syntax error
            (BACK-1084's structure['_has_errors']) -- detections for this file may be
            incomplete or wrong, not just "clean" (BACK-1083).
        parse_error_reason: An analyzer's explicit source-invalidity reason, when
            degradation is known without native parser recovery.
        rule_errors: Rules that raised during check() ({"rule", "error"})
            (BACK-1083).
        no_snippets: Omit each detection's `context` (code excerpt) field (BACK-1182).
        max_snippet_chars: Truncate each detection's `context` to N chars instead of
            omitting it (BACK-1181). Ignored when no_snippets.
        total_available: True detection count before any --max-items truncation, if
            different from len(detections) (BACK-1181).
        disclosures: Rules in the effective set that skipped this file's language
            (capability_disclosures, BACK-1466); emitted as ``scan_disclosures``, the
            key recursive check's summary uses.
        coverage: Per-rule outcomes for this file (``CoverageTally.report``, BACK-2137), emitted
            as ``coverage``, the key a directory check and ``reveal://`` carry.
    """
    from reveal.utils.path_utils import to_posix
    from reveal.utils.results import note_truncation

    path = to_posix(path)  # '/' on every OS, like the directory envelope (BACK-1366)
    result = {
        'file': path,
        'detections': [
            d.to_dict(no_snippets=no_snippets, max_snippet_chars=max_snippet_chars)
            for d in detections
        ],
        'total': len(detections),
        # BACK-1466: [] means every rule in the set looked at this file.
        'scan_disclosures': list(disclosures or []),
    }
    if total_available is not None and total_available != len(detections):
        result['meta'] = {
            'truncated': True,
            'total_available': total_available,
            'returned': len(detections),
        }
        note_truncation(result, 'detections', len(detections), total_available,
                        cause='max_items')
    if parse_degraded:
        result['warning'] = (
            f"{parse_error_description(parse_error_at, parse_error_reason)}; "
            "results may be incomplete or incorrect"
        )
    if rule_errors:
        result['errors'] = rule_errors
    if coverage is not None:
        result['coverage'] = coverage
    return result


def _detections_json(path: str, result: dict) -> str:
    """The document ``--format json`` prints for a single-file *result*: what --also-json
    writes beside a text or grep render (BACK-1248)."""
    from reveal.cli.routing.subcommand import subcommand_json
    return subcommand_json(result, name='check', source=path, source_type='file')


@dataclass
class CheckSinkCollection:
    """The native stdin check's existing aggregate plus requested rendered streams."""
    results: List[dict] = field(default_factory=list)
    chunks: Dict[str, List[str]] = field(default_factory=dict)

    def append(self, result: dict, bodies: Dict[str, str]) -> None:
        # Aggregate rows keep their established raw file-result shape; provenance is on the aggregate.
        self.results.append({key: value for key, value in result.items() if key != 'execution'})
        for fmt, body in bodies.items():
            self.chunks.setdefault(fmt, []).append(body)

    def document(self, fmt: str) -> str:
        return stdin_check_artifact(self.results) if fmt == 'json' else ''.join(self.chunks.get(fmt, []))


def write_check_artifact(fmt: str, path: str, document: str, result: Optional[dict] = None) -> bool:
    """Use the shared requested-output failure policy for an already rendered check view."""
    def write() -> None:
        try:
            write_text_artifact(path, document)
        except ARTIFACT_WRITE_ERRORS as exc:
            setattr(exc, 'sink_format', fmt)
            raise
    return write_requested_artifact(write, result) is not None


def stdin_check_artifact(results: List[dict]) -> str:
    """The one document a ``--stdin --check`` run writes to its json sinks (BACK-2095): every file's result
    in input order under ``files``, with the totals the directory report keeps in ``summary``."""
    from reveal.cli.routing.subcommand import subcommand_json
    report = {
        'files': results,
        'summary': {
            'files_checked': len(results),
            'files_with_issues': sum(1 for r in results if r['total']),
            'total_issues': sum(r['total'] for r in results),
        },
    }
    return subcommand_json(report, name='check', source='stdin', source_type='stdin')


def _emit_detections(path: str, output_format: str, detections: List[Any],
                     rendered: List[Any], no_group: bool = False,
                     scan_incomplete: bool = False, **result_fields: Any) -> dict:
    """Print a single-file check's result through the subcommand seam and return it.

    JSON gets its envelope there, text/grep are rendered by it, and a --max-items cut
    is disclosed once after the render (BACK-1702). *rendered* is *detections* after
    --max-items; grep prints every detection, as it always has, so its result carries
    no cut. *result_fields* are _detections_result's (parse_degraded, rule_errors,
    no_snippets, max_snippet_chars, total_available, disclosures). *scan_incomplete*
    only selects the text verdict (BACK-1826). The returned result is the one for
    *rendered*, which --also-json writes.
    """
    from argparse import Namespace
    from reveal.cli.routing.subcommand import emit_subcommand_result

    coverage_selected = result_fields.pop('coverage_selected', False)
    result: dict = attach_provenance(_detections_result(path, rendered, **result_fields))
    printed = _detections_result(path, detections, **result_fields) \
        if output_format == 'grep' else result

    def render(_result: dict) -> None:
        if output_format == 'grep':
            _format_detections_grep(detections)
        else:
            _format_detections_text(
                path, rendered, no_group=no_group,
                parse_degraded=result_fields.get('parse_degraded', False),
                parse_error_at=result_fields.get('parse_error_at'),
                parse_error_reason=result_fields.get('parse_error_reason'),
                rule_errors=result_fields.get('rule_errors'),
                no_snippets=result_fields.get('no_snippets', False),
                max_snippet_chars=result_fields.get('max_snippet_chars'),
                disclosures=result_fields.get('disclosures'),
                scan_incomplete=scan_incomplete,
                coverage=result_fields.get('coverage'),
                coverage_selected=coverage_selected,
            )

    emit_subcommand_result(printed, Namespace(format=output_format), name='check', source=path,
                           render=render, source_type='file')
    return result


def _format_detections_grep(detections: List[Any]) -> None:
    """Format detections as grep output.

    Args:
        detections: List of Detection objects
    """
    for d in detections:
        print(f"{d.file_path}:{d.line}:{d.column}:{d.rule_code}:{d.message}")


def _print_run_notes(path: str, rule_errors: Optional[List[dict]], disclosures: Optional[List[str]],
                     coverage: Optional[dict], coverage_selected: bool) -> None:
    """What a single-file check says about the run itself, before the findings or the verdict:
    crashed rules, scan disclosures, then the rules that did not run clean (BACK-2137)."""
    from reveal.rendering.adapters.reveal import render_check_coverage

    for err in rule_errors or []:
        print(f"{path}: ⚠️  rule {err['rule']} crashed and did not run — {err['error']}")
    for note in disclosures or []:
        print(f"{path}: ⚠️  {note}")
    render_check_coverage(coverage, selected=coverage_selected, said=disclosures or ())


def _format_detections_text(
    path: str,
    detections: List[Any],
    no_group: bool = False,
    parse_degraded: bool = False,
    parse_error_at: Optional[Tuple[int, int]] = None,
    rule_errors: Optional[List[dict]] = None,
    no_snippets: bool = False,
    max_snippet_chars: Optional[int] = None,
    disclosures: Optional[List[str]] = None,
    scan_incomplete: bool = False,
    parse_error_reason: Optional[str] = None,
    coverage: Optional[dict] = None,
    coverage_selected: bool = False,
) -> None:
    """Format detections as human-readable text.

    When a rule fires >= _GROUP_THRESHOLD times, collapses to a single summary
    line to keep output scannable.  Use --no-group to expand everything.

    Args:
        path: File path
        detections: List of Detection objects (already max-items-truncated
            by the caller, if requested — this just renders what it's given;
            the cut is disclosed by the subcommand seam, BACK-1702)
        no_group: Disable collapsing of repeated rules
        parse_degraded: True when the parser recovered from a syntax error —
            see _format_detections_json (BACK-1083).
        parse_error_reason: An explicit invalid-source reason instead of the
            generic recovery description.
        rule_errors: Rules that raised during check() — see _format_detections_json.
        no_snippets: Omit the 📝 code-excerpt line (BACK-1182).
        max_snippet_chars: Truncate the excerpt to N chars instead of
            omitting it (BACK-1181). Ignored when no_snippets.
        disclosures: Rules that skipped this file's language (BACK-1466),
            printed before the verdict so a ✅ can't read as a full check.
        scan_incomplete: True when the exit code is 3 for a reason other than this
            file's parse (a capped/skipped or partly unparsed project-wide scan). The
            verdict says "scan incomplete" exactly when the exit code does (BACK-1826);
            a language gap alone is a note, not an incomplete scan.
        coverage: this file's rule outcomes (BACK-2137), printed as the shared ``Checks:`` block
            before the verdict; *coverage_selected*: --select named the rules, so the rules not
            applicable to the file print too (render_check_coverage).
    """
    _print_run_notes(path, rule_errors, disclosures, coverage, coverage_selected)

    if not detections:
        if parse_degraded:
            print(f"{path}: ⚠️  {parse_error_description(parse_error_at, parse_error_reason)}"
                  " — results may be incomplete or incorrect")
        else:
            if rule_errors or scan_incomplete:
                verdict = "⚠️  No findings in the checked population; scan incomplete"
            elif disclosures:
                verdict = "✅ No issues found (see the notes above)"
            else:
                verdict = "✅ No issues found"
            print(f"{path}: {verdict}")
        return

    count = len(detections)
    if parse_degraded:
        print(f"{path}: ⚠️  {parse_error_description(parse_error_at, parse_error_reason)}"
              " — results below may be incomplete or incorrect")
    print(f"{path}: Found {count} issue{'s' if count != 1 else ''}\n")

    if no_group or count < _GROUP_THRESHOLD:
        for d in sorted(detections, key=lambda x: (x.line, x.column)):
            print(d.render(no_snippets=no_snippets, max_snippet_chars=max_snippet_chars))
            print()
        return

    # Group by rule_code to find repeated rules
    by_rule: dict = defaultdict(list)
    for d in detections:
        by_rule[d.rule_code].append(d)

    collapsed: set = {code for code, group in by_rule.items() if len(group) >= _GROUP_THRESHOLD}
    shown_collapsed: set = set()

    for d in sorted(detections, key=lambda x: (x.line, x.column)):
        if d.rule_code not in collapsed:
            print(d.render(no_snippets=no_snippets, max_snippet_chars=max_snippet_chars))
            print()
        elif d.rule_code not in shown_collapsed:
            shown_collapsed.add(d.rule_code)
            total = len(by_rule[d.rule_code])
            print(d.render(no_snippets=no_snippets, max_snippet_chars=max_snippet_chars))
            print(f"\n  ↳ +{total - 1} more {d.rule_code} occurrences hidden — use --no-group to expand\n")


def _analyzer_error_position(analyzer: Any) -> Optional[Tuple[int, int]]:
    """The first parse error's (line, column), for analyzers that can say (BACK-1779)."""
    locate = getattr(analyzer, 'first_parse_error_position', None)
    return locate() if callable(locate) else None


def structure_parse_degraded(structure: Any) -> bool:
    """True when the file did not parse cleanly, so "no issues" is not a clean bill.

    `_has_errors` (BACK-1084) is set by TreeSitterAnalyzer.get_structure, by every
    override of it (BACK-1589: the base class wraps them, so JSON, YAML, TOML, ...
    no longer need their tree asked here, which BACK-1404 did after truncated JSON
    read "✅ No issues"), and by analyzers whose own parser failed (XML, notebooks,
    JSONL).
    """
    return isinstance(structure, dict) and bool(structure.get('_has_errors'))


def _capture_file_check(analyzer: FileAnalyzer, path: str, fmt: str, args: Any, config: Any,
                        detections: list, rendered: list, fields: dict) -> Tuple[dict, str, str]:
    output, errors = io.StringIO(), io.StringIO()
    with redirect_stdout(output), redirect_stderr(errors):
        if fmt == 'text' and _is_generated_file(analyzer.content):
            print(f"{path}: ℹ️  Auto-generated file detected — results may include unfixable issues\n"
                  "  💡 Add '# reveal: generated' near the top to suppress in recursive checks\n")
        result = _emit_detections(path, fmt, detections, rendered, **fields)
        if fmt == 'text':
            print_breadcrumbs('quality-check', path, file_type=get_file_type_from_analyzer(analyzer),
                             config=config, detections=detections)
    return result, output.getvalue(), errors.getvalue()


def _emit_check_outputs(analyzer: FileAnalyzer, path: str, output_format: str, args: Any,
                        config: Any, detections: list, rendered: list,
                        collect: Optional[CheckSinkCollection], **fields: Any) -> bool:
    sinks = file_sinks(args)
    formats = {output_format, *(fmt for fmt, _ in sinks)}
    if sinks:
        formats.add('json')
    views = {fmt: _capture_file_check(analyzer, path, fmt, args, config, detections, rendered, fields)
             for fmt in sorted(formats)}
    primary, body, errors = views[output_format]
    failed = False
    if collect is not None:
        collect.append(views['json'][0], {fmt: views[fmt][1] for fmt, _ in sinks if fmt != 'json'})
    else:
        for fmt, destination in sinks:
            document = views[fmt][1]
            failed = write_check_artifact(fmt, destination, document, primary) or failed
    if errors:
        # boundary-ok: print -- replay the existing check renderer's captured diagnostics once.
        print(errors, end='', file=sys.stderr)
    if output_format == 'json' and failed:
        # Rebuild only when requested writes added errors after the primary view was rendered.
        # boundary-ok: print -- the existing subcommand JSON seam rebuilds only added output errors.
        print(_detections_json(path, primary))
    else:
        # boundary-ok: print -- replay the existing check renderer's captured primary view.
        print(body, end='')
    return failed


def run_pattern_detection(
    analyzer: FileAnalyzer,
    path: str,
    output_format: str,
    args: Any,
    config: Optional[Any] = None,
    collect: Optional[CheckSinkCollection] = None,
) -> Tuple[int, bool, bool]:
    """Run pattern detection rules on a file.

    Args:
        analyzer: File analyzer instance
        path: File path
        output_format: Output format ('text', 'json', 'grep')
        args: CLI arguments (for --select, --ignore)
        config: Optional RevealConfig for breadcrumb settings
        collect: A --stdin run's canonical results and requested rendered streams, written once
            per destination at the end of the invocation (BACK-2095).

    Returns:
        (detection_count, degraded, artifact_failed) tuple. `degraded` is True when the file
        did not parse cleanly (BACK-1083's parse_degraded, tree-sitter
        error-recovery) or a rule raised (rule_errors) -- meaning
        `detection_count` may be incomplete/wrong, not a trustworthy
        "clean" signal. Added for BACK-1099's exit-code contract: a caller
        that only wants the old int should unpack `count, _, _ = run_pattern_detection(...)`.
        `artifact_failed` is True when a requested artifact (``--also-json``) could not be
        written: a required output failure, exit 3 (BACK-1939), disclosed on stderr here.
    """
    from .rules import CoverageTally, RuleRegistry

    # Parse select/ignore options
    select = args.select.split(',') if args.select else None
    ignore = args.ignore.split(',') if args.ignore else None
    no_group = getattr(args, 'no_group', False)
    no_snippets = getattr(args, 'no_snippets', False)
    severity_arg = getattr(args, 'severity', None)

    # Get structure and content
    structure = analyzer.get_structure()
    content = analyzer.content

    # Run rules
    rule_errors: List[dict] = []
    ledger: List[dict] = []
    detections = RuleRegistry.check_file(
        path, structure, content, select=select, ignore=ignore, errors=rule_errors, coverage=ledger
    )
    outcomes = CoverageTally()
    outcomes.add(ledger)
    # BACK-1083: a tree-sitter recovery parse (structure['_has_errors'], set by
    # BACK-1084) means rules ran against fabricated/partial structure — surface
    # that instead of letting "0 detections" read as "clean file".
    parse_degraded = structure_parse_degraded(structure)
    # BACK-1466: the same rule/language gaps recursive check discloses (W-CAP-1
    # T006, W-CAP-2 I001) -- without them a single-file ✅ claims more than ran.
    from reveal.rules.scan_caches import get_scan_disclosures
    scan_disclosures = get_scan_disclosures([Path(path)], select, ignore)
    disclosures = scan_disclosures + capability_disclosures([path], select, ignore)

    # Apply severity filter if requested
    if severity_arg:
        _SEVERITY_ORDER = ['low', 'medium', 'high', 'critical']
        level = severity_arg.lower()
        if level not in _SEVERITY_ORDER:
            print(f"Warning: unknown --severity '{severity_arg}'. Valid levels: {', '.join(_SEVERITY_ORDER)}",
                  file=sys.stderr)
        else:
            min_idx = _SEVERITY_ORDER.index(level)
            detections = [d for d in detections
                          if _SEVERITY_ORDER.index(d.severity.value) >= min_idx]

    # BACK-1181: --max-items caps what's RENDERED, not the true count -- the
    # return value below (and thus check_exit_code's total_issues) must
    # still reflect reality, or a truncated view could silently mask
    # findings from the exit code / summary.
    max_items = getattr(args, 'max_items', None)
    max_snippet_chars = getattr(args, 'max_snippet_chars', None)
    total_available = len(detections)
    rendered_detections = detections
    if max_items is not None and total_available > max_items:
        rendered_detections = detections[:max_items]

    artifact_failed = _emit_check_outputs(
        analyzer, path, output_format, args, config, detections, rendered_detections, collect,
        no_group=no_group, parse_degraded=parse_degraded, rule_errors=rule_errors,
        no_snippets=no_snippets,
        parse_error_at=_analyzer_error_position(analyzer) if parse_degraded else None,
        parse_error_reason=structure.get('error'), max_snippet_chars=max_snippet_chars,
        total_available=total_available, disclosures=disclosures,
        scan_incomplete=bool(scan_disclosures), coverage=outcomes.report(len(rule_errors)),
        coverage_selected=bool(select),
    )

    degraded = parse_degraded or bool(rule_errors) or bool(scan_disclosures)
    return len(detections), degraded, artifact_failed


def run_schema_validation(
    analyzer: FileAnalyzer,
    path: str,
    schema_name: str,
    output_format: str,
    args: Any
) -> None:
    """Run schema validation on front matter.

    Args:
        analyzer: File analyzer instance
        path: File path
        schema_name: Schema name or path to schema file
        output_format: Output format ('text', 'json', 'grep')
        args: CLI arguments (for --select, --ignore)
    """
    from .schemas.frontmatter import load_schema
    from .registry import get_markdown_extensions

    # Check if file is markdown (schema validation is for markdown front matter)
    if not path.lower().endswith(tuple(get_markdown_extensions())):
        print("Warning: Schema validation is designed for markdown files", file=sys.stderr)
        print(f"         File '{path}' does not appear to be markdown", file=sys.stderr)
        print("         Continuing anyway...\n", file=sys.stderr)

    # Load schema
    schema = load_schema(schema_name)
    if not schema:
        print(f"Error: Schema '{schema_name}' not found", file=sys.stderr)
        print("\nAvailable built-in schemas:", file=sys.stderr)
        from .schemas.frontmatter import list_schemas
        for name in list_schemas():
            print(f"  - {name}", file=sys.stderr)
        print("\nOr provide a path to a custom schema file", file=sys.stderr)
        sys.exit(2)

    detections, degraded, errors = collect_schema_detections(analyzer, path, schema, args)
    _emit_detections(path, output_format, detections, detections,
                     parse_degraded=degraded, rule_errors=errors)
    if detections or degraded or errors:
        sys.exit(1)


def collect_schema_detections(analyzer: FileAnalyzer, path: str, schema: dict,
                              args: Any) -> Tuple[List[Any], bool, List[dict]]:
    """Collect one validation without emitting or exiting; shared by file and stdin.

    Returns detections, parse degradation and rule errors. Schema context belongs to
    this call and is cleared even if structure extraction or a rule fails.
    """
    from .rules.frontmatter import set_validation_context, clear_validation_context
    from .rules import CoverageTally, RuleRegistry

    structure = analyzer.get_structure(extract_frontmatter=True)
    errors: List[dict] = []
    set_validation_context(schema)
    try:
        select = args.select.split(',') if args.select else ['F']
        ignore = args.ignore.split(',') if args.ignore else None
        detections = RuleRegistry.check_file(
            path, structure, analyzer.content, select=select, ignore=ignore, errors=errors)
        return detections, structure_parse_degraded(structure), errors
    finally:
        clear_validation_context()
