"""BACK-2627 (S3b-1, C1): ``add_declared_arguments`` generates a declaration's arguments onto a parser that already owns
some of its flags.

The element views are declared (X1) and their arguments are generated onto the main parser, which already owns
``--depth``, ``--range``, ``--head`` and ``--tail`` for the other path-read answers. A control whose flags the parser
owns is not generated again (its value is that argument's); the path read keeps its own positional (no resource). A
declared noun's parser owns none of its controls' flags before generation, so nothing changes for them.
"""
import argparse

import pytest

from reveal.cli.invocation import COMMANDS
from reveal.cli.routing.declared import create_declared_parser, declared_adapter_class
from reveal.utils.query_binding import add_declared_arguments
from reveal.utils.query_parser import CliBinding, LegacySpelling, ParamSpec, ResourceSpec, whole_number


def _main_like_parser():
    parser = argparse.ArgumentParser(add_help=False)
    parser.add_argument('path', nargs='?')
    parser.add_argument('--depth', type=int, default=None, help='the path read\'s own depth')
    return parser


DEPTH = ParamSpec('depth', 'integer', 'hops', None, whole_number, cli=CliBinding(('--depth',)))
NESTING = ParamSpec('nesting-depth', 'integer', 'structural depth', None, whole_number,
                    cli=CliBinding(('--nesting-depth',), dest='nesting_depth'))
VIEW = ParamSpec('view', 'string', 'answer', None, str, choices=('a', 'b'), role='operation',
                 cli=CliBinding(('--view',)), legacy=(LegacySpelling('boundary', flag='--old-a', flag_value='a'),))


def test_a_control_whose_flag_the_parser_owns_is_not_generated_again():
    parser = _main_like_parser()
    owner = parser._option_string_actions['--depth']
    add_declared_arguments(parser, (DEPTH, NESTING, VIEW), None)
    assert parser._option_string_actions['--depth'] is owner  # the path read's argument stays the owner
    assert parser.parse_args(['f', '--depth', '3']).depth == 3
    args = parser.parse_args(['f', '--nesting-depth', '2', '--view', 'b'])
    assert (args.nesting_depth, args.view) == ('2', 'b')  # a generated argument stores what was typed; the binder converts
    assert vars(parser.parse_args(['f', '--old-a']))['boundary'] == 'a'  # legacy flags are still generated


def test_no_resource_adds_no_positional():
    parser = _main_like_parser()
    before = [action.dest for action in parser._actions if not action.option_strings]
    add_declared_arguments(parser, (NESTING,), None)
    assert [action.dest for action in parser._actions if not action.option_strings] == before


def test_sibling_a_resource_still_adds_its_positional():
    parser = argparse.ArgumentParser(add_help=False)
    add_declared_arguments(parser, (NESTING,), ResourceSpec())
    assert parser.parse_args(['src']).path == 'src'


def test_an_owned_flag_with_another_destination_is_a_declaration_error():
    """A declaration naming a flag another control owns would read that control's value: refused at build time."""
    parser = _main_like_parser()
    other = ParamSpec('hops', 'integer', 'hops', None, whole_number, cli=CliBinding(('--depth',)))
    with pytest.raises(ValueError, match='--depth'):
        add_declared_arguments(parser, (other,), None)


@pytest.mark.parametrize('noun', sorted(name for name, spec in COMMANDS.items() if spec.declared_adapter))
def test_every_declared_noun_generates_every_control_flag_itself(noun):
    """Effect on other nouns: none. Every flag of every declared control is generated by its own declaration (the
    argument's dest is the control's), so the skip never applies to a noun's parser."""
    parser = create_declared_parser(noun)
    for spec in declared_adapter_class(noun).PARAM_SPECS:
        if spec.cli is None:
            continue
        for flag in spec.cli.flags:
            action = parser._option_string_actions[flag]
            assert action.dest == (spec.cli.dest or spec.name), (noun, flag, action.dest)
