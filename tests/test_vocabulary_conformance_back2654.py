def _adapter(noun):
    if noun == ELEMENT:  # the element pseudo-noun's declarations (BACK-2627 S3b-5): no adapter, the file route's specs
        return _ElementNoun
    return declared_adapter_class(noun) if noun in COMMANDS else get_adapter_class(noun)


def _specs(noun):
    """The noun's declared controls. A flag-only legacy modifier (ParamSpec.flag_only: --head, --check) is none: it has
    no URI key, keyword or schema entry to probe; column 23 reaches its flag from the parsers, and
    tests/test_legacy_slice_flags_back2673.py and tests/test_legacy_claude_and_check_flags_back2673.py hold it."""
    return [spec for spec in _adapter(noun).PARAM_SPECS if not spec.flag_only]


def _named_entries(spec):
    """The legacy entries keyed by name alone (a value-keyed entry such as AST ``show=calls`` is one value's row;
    JSON's first-position selectors are bare words, deferred by D18)."""
    return [entry for entry in getattr(spec, 'legacy', ())
            if getattr(entry, 'value', None) is None and not getattr(entry, 'first', False)]


def _other_spellings(spec):
    """Every spelling of a control besides its name: spelling variants (aliases) and its legacy words."""
    return (*spec.aliases, *(entry.name for entry in _named_entries(spec)))


def _entry(spec, spelling):
    return next((entry for entry in _named_entries(spec) if entry.name == spelling), None)


def _implied(entry, raw):
    """(control, value) for each control a legacy word sets besides its owner (``LegacySpelling.sets``, BACK-2614:
    Markdown ``aggregate=F`` is ``field=F`` and ``view=aggregate``): the canonical request it answers as names them too."""
    if entry is None or not getattr(entry, 'sets', ()):
        return []
    return [(control, value) for control, value in entry.translate(raw).items()
            if control != entry.owner and value is not None]


def _implied_pairs(entry, raw):
    return [f'{control}={value}' for control, value in _implied(entry, raw)]


def _implied_flags(entry, raw):
    return [f'--{control.replace("_", "-")}={value}' for control, value in _implied(entry, raw)]


def _spec_for(noun, key):
    return next((spec for spec in _specs(noun) if key in (spec.name, *_other_spellings(spec))), None)


def _uri(noun, *pairs, base=True, control=None):
    """The noun's default URI plus *pairs*; ``base=False`` drops its default operation (an operation control
    under test would otherwise be a second mode). *control* names the control under test (CONTROL_TARGETS,
    CONTROL_BASES)."""
    query = CONTROL_BASES.get((noun, control), BASE[noun])[1].lstrip('?') if base else ''
    parts = [part for part in (query, *pairs) if part]
    target = CONTROL_TARGETS.get((noun, control), TARGETS.get(noun, 'proj'))
    return f'{noun}://{target}' + ('?' + '&'.join(parts) if parts else '')


def _sub(noun, *extra, base=True, control=None):
    """The subcommand argv, or None when the noun has no subcommand. The element pseudo-noun's is its path read,
    ``FILE ELEMENT [view] *extra`` (BACK-2627 S3b-5)."""
    if noun == ELEMENT:
        element, view = ELEMENT_REQUESTS.get(control, ELEMENT_REQUESTS[None])[:2]
        return [ELEMENT_FILE, element, *(view if base else ()), *extra]
    cli = BASE[noun][0] if BASE[noun][0] is None else CONTROL_BASES.get((noun, control), BASE[noun])[0]
    target = CONTROL_TARGETS.get((noun, control), TARGETS.get(noun, 'proj'))
    return None if cli is None else [noun, target, *(cli if base else ()), *extra]


@dataclass(frozen=True)
class Run:
    argv: tuple
    rc: object  # the exit code, or 'crash' when reveal raised out of main()
    out: str
    err: str

    def says(self, *words):
        return all(word in self.err for word in words)

    def brief(self):
        lines = [line.strip() for line in self.err.splitlines()
                 if line.strip() and not line.startswith(('usage:', ' '))]
        plain = next((line for line in lines if not line.startswith('note:')), '')
        first = next((line for line in lines if 'rror' in line), plain)
        return f"`reveal {' '.join(self.argv)}` -> exit {self.rc}" + (f': {first[:160]}' if first else '')


def _run(*argv):
    try:
        result = _run_reveal_direct(*argv)
    except Exception as exc:  # an uncaught error is a measured outcome (a crash), not a broken probe
        return Run(tuple(argv), 'crash', '', f'{type(exc).__name__}: {exc}')
    return Run(tuple(argv), result.returncode, result.stdout, result.stderr)


def _spellings(noun):
    """Every spelling of each declared control (name, aliases, flags, global flags reaching it) -> its name."""
    names = {}
    for spec in _specs(noun):
        for spelling in (spec.name, *_other_spellings(spec), *(spec.cli.flags if spec.cli else ())):
            names[spelling] = spec.name
        for entry in _named_entries(spec):
            if getattr(entry, 'flag', None):
                names[entry.flag] = spec.name
        for flag, _value in spec.cli_flags:
            names[f'--{flag}'] = spec.name
    for flag in FLAG_SPECS:
        fragment = _received(noun, flag)
        if fragment is not None:
            key = fragment.partition('=')[0]
            names[flag.option] = names.get(key, key)
    # The gitignore walk policy reaches every walking noun through its own switch, not a declared control (BACK-2721).
    from reveal.cli.global_flags import add_gitignore_arguments
    switch = argparse.ArgumentParser(add_help=False)
    add_gitignore_arguments(switch)
    for action in switch._actions:
        names.update(dict.fromkeys(action.option_strings, action.dest))
    return names


def _answer(run, noun):
    """What a request answered: exit and stdout. Retirement facts name the spelling used, and an unused-input
    warning names the control as the caller spelled it, so both are compared by the control they name."""
    try:
        doc = json.loads(run.out)
    except ValueError:
        return run.rc, run.out
    names = _spellings(noun)
    for key in ('meta', 'metadata'):  # `metadata` is meta's additive-stage alias on an imports answer: the same warnings
        meta = doc.get(key) if isinstance(doc, dict) else None
        if not (isinstance(meta, dict) and 'warnings' in meta):
            continue
        warnings = []
        for warning in meta['warnings']:
            if warning.get('code') == 'retired_spelling':
                continue
            if warning.get('code') in ('unused_flag', 'unused_query_param'):
                fields = sorted({names.get(field, field) for field in warning.get('fields', [])})
                warning = {'code': 'unused_input', 'fields': fields}
            if warning not in warnings:  # two spellings of one unused control are one fact
                warnings.append(warning)
        meta['warnings'] = warnings
        if not warnings and set(meta) == {'warnings'}:  # an answer with no meta of its own gained one only to carry a note
            del doc[key]
    return run.rc, doc


@dataclass(frozen=True)
class Case:
    label: str
    ok: bool
    evidence: str


def _error_message(run):
    """The request's own error: the JSON document's ``error``, else stderr without its notes. A retirement note
    beside the error names a spelling too, so it cannot stand in for the error naming it."""
    try:
        doc = json.loads(run.out)
    except ValueError:
        doc = None
    if isinstance(doc, dict) and isinstance(doc.get('error'), str):
        return doc['error']
    return '\n'.join(line for line in run.err.splitlines() if not line.lower().startswith('note:'))


def _conflict_case(label, conflict, names):
    """Rule 1, different values: exit 2, the error naming both spellings as the request typed them."""
    message = _error_message(conflict)
    return Case(f'{label} conflict', conflict.rc == 2 and conflict.says(*names) and all(n in message for n in names),
                f'{conflict.brief()} (wants exit 2, the error naming {" and ".join(names)})')


def _equal_case(label, noun, pair, single):
    """Rule 1, equal values: the same answer as the value given once."""
    return Case(f'{label} equal', _answer(pair, noun) == _answer(single, noun),
                f'{pair.brief()} answers differently from {single.brief()}')


