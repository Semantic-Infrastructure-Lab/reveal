# --- rule 1b: an alias and its name -----------------------------------------------------------------------

def _candidate_values(spec):
    """Values of *spec* to try, the declaration's own first."""
    if spec.type in ('boolean', 'flag'):
        return ['true', 'false']
    choices = [str(choice) for choice in spec.choices if choice]
    if choices:
        return choices
    if spec.type in ('integer', 'number'):
        low = spec.minimum or 0
        return [str(low + 2), str(low + 1)]
    spellings = (spec.name, *_other_spellings(spec))
    # An example may name the answer that reads the control first (xlsx 'sheet=0&cells=A1:C10'): its own part counts.
    names = {name.replace('-', '_') for name in spellings}
    example = next((value for key, value in _example_pairs(spec) if key.replace('-', '_') in names), '')
    return [example or 'function', 'other']


def _example_pairs(spec):
    """(key, value) for each control a declared example names: its flags (``--sheet 0 --cells A1:C10``, a
    ``reveal NOUN PATH --flags`` command; BACK-2713), or a query fragment (``sheet=0&cells=A1:C10``)."""
    for example in spec.examples:
        if not (example.startswith(('-', 'reveal ')) or ' --' in example):
            for part in example.split('&'):
                key, _, value = part.lstrip('?').partition('=')
                yield key, value
            continue
        words = shlex.split(example)
        while words:
            word = words.pop(0)
            if word.startswith('--'):
                key, eq, value = word[2:].partition('=')
                if not eq and words and not words[0].startswith('-'):
                    value = words.pop(0)
                yield key, value


def _alias_spelling(spec, alias, value):
    """How *alias* spells *value*: the value itself, or the legacy form its translation maps to it."""
    entry = _entry(spec, alias)
    normalize = getattr(spec, 'alias_normalize', None)
    if entry is not None:
        translate = lambda candidate: dict(entry.translate(candidate)).get(spec.name)  # noqa: E731
    elif normalize is not None:
        translate = lambda candidate: normalize(alias, candidate)  # noqa: E731
    else:
        return value
    for candidate in (value, value.lstrip('-'), 'true'):
        try:
            if translate(candidate) == value:
                return candidate
        except ValueError:
            continue
    return None


def _alias_values(spec, alias):
    """(value, the alias's spelling of it, a different valid value or None)."""
    values = _candidate_values(spec)
    for value in values:
        same = _alias_spelling(spec, alias, value)
        if same is not None:
            return value, same, next((other for other in values if other != value), None)
    return None


def _flag_spelling(spec, name):
    entry = _entry(spec, name)
    if entry is not None and getattr(entry, 'flag', None):
        return entry.flag
    if spec.cli is None:
        return None
    return next((flag for flag in spec.cli.flags if flag[2:] in (name, name.replace('_', '-'))), None)


def _alias_on_subcommand(noun, spec, alias, values):
    name_flag, alias_flag = _flag_spelling(spec, spec.name), _flag_spelling(spec, alias)
    legacy = dict(spec.cli_flags).get(alias)  # a global flag that spells the alias (--verbose is detail=full)
    if _sub(noun) is None or name_flag is None:
        return []
    value, same, other = values
    base = spec.role != 'operation'
    entry = _entry(spec, alias)
    if entry is not None and getattr(entry, 'flag_value', None) is not None and alias_flag:
        value = entry.translate(entry.flag_value)[spec.name]
        # a control with one valid value cannot be given two (sqlite --view health and its --check, BACK-2626)
        other = None if [str(choice) for choice in spec.choices if choice] == [value] else _other(spec, value)
        conflict = _sub(noun, f'{name_flag}={other}', alias_flag, base=base) if other else None
        pair = _sub(noun, f'{name_flag}={value}', alias_flag, base=base)
        names = (name_flag, alias_flag)
    elif alias_flag is not None and alias_flag != name_flag:
        conflict = _sub(noun, f'{name_flag}={other}', f'{alias_flag}={same}', base=base) if other else None
        pair = _sub(noun, f'{name_flag}={value}', f'{alias_flag}={same}', base=base)
        names = (name_flag, alias_flag)
    elif legacy is not None:
        value, other = legacy, _other(spec, legacy)
        conflict = _sub(noun, f'{name_flag}={other}', f'--{alias}', base=base)
        pair = _sub(noun, f'{name_flag}={value}', f'--{alias}', base=base)
        names = (name_flag, f'--{alias}')
    else:
        return []
    label = f'{names[0]} vs {names[1]}'
    cases = [_conflict_case(label, _run(*conflict, '--format', 'json'), names)] if conflict else []
    single = _sub(noun, f'{name_flag}={value}', *_implied_flags(entry, same), base=base)
    return cases + [_equal_case(label, noun, _run(*pair, '--format', 'json'), _run(*single, '--format', 'json'))]


def probe_alias_and_name(noun):
    cases = []
    for spec in _specs(noun):
        if _repeatable(spec):
            continue  # a repeatable control's spellings accumulate (rule 1): column 1d
        for alias in _other_spellings(spec):
            values = _alias_values(spec, alias)
            if values is None:
                continue
            value, same, other = values
            base = spec.role != 'operation'
            label = f'?{spec.name}= vs ?{alias}='
            if other is not None:  # a control with one valid value cannot be given two
                conflict = _uri(noun, f'{spec.name}={other}', f'{alias}={same}', base=base, control=spec.name)
                cases.append(_conflict_case(label, _run(conflict, '--format', 'json'), (spec.name, alias)))
            pair = _uri(noun, f'{spec.name}={value}', f'{alias}={same}', base=base, control=spec.name)
            single = _uri(noun, f'{spec.name}={value}', *_implied_pairs(_entry(spec, alias), same), base=base,
                          control=spec.name)
            cases.append(_equal_case(label, noun, _run(pair, '--format', 'json'), _run(single, '--format', 'json')))
            cases += _alias_on_subcommand(noun, spec, alias, values)
    return cases


